# Regenerate docs/agents/hot-files.md from history and live branches.
# A generated list cannot go stale quietly, and it cannot conflict.
#
#   tools/agents/hot-files.sh                # rewrite the doc
#   tools/agents/hot-files.sh --print        # stdout only
#   tools/agents/hot-files.sh --window 90 --branches 40

here="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=tools/agents/lib.sh
. "$here/lib.sh"

window=180
branch_days=60
max_branches=40
out="docs/agents/hot-files.md"
print_only=false

while [ $# -gt 0 ]; do
    case "$1" in
    -h | --help)
        cat <<'EOF'
Usage: tools/agents/hot-files.sh [--window DAYS] [--branches N] [--print]

  --window DAYS   history window for author counts (default 180)
  --branches N    how many active branches to scan (default 40)
  --print         print instead of writing docs/agents/hot-files.md
EOF
        exit 0
        ;;
    --window)
        window="${2:-180}"
        shift 2
        ;;
    --branches)
        max_branches="${2:-40}"
        shift 2
        ;;
    --print)
        print_only=true
        shift
        ;;
    *)
        agent_die "unknown argument $1"
        ;;
    esac
done

root="$(agent_repo_root)"
cd "$root"
trunk="$(agent_trunk_ref)" || agent_die "no master ref; git fetch origin master:master"

tmp_authors="$(mktemp)"
tmp_raw="$(mktemp)"
tmp_branches="$(mktemp)"
trap 'rm -f "$tmp_authors" "$tmp_raw" "$tmp_branches"' EXIT

# Distinct authors per file over the window. Two different questions get asked
# about hot files ("who argues about this one" vs "which branches collide next
# week"), so both are measured.
# Bot-owned trees churn weekly and are never worth a conflict: keep them out of
# the list so the list stays about code people argue over.
skip_re='^(externals/|LICENSES/|dist/languages/|dist/qt_themes/|src/android/app/src/main/res/values-[a-zA-Z-]+/)'

git log --since="$window days ago" --format='A %an' --name-only "$trunk" 2>/dev/null |
    awk -v skip="$skip_re" '
        /^A / { author = substr($0, 3); next }
        NF && $0 !~ skip { seen[$0 SUBSEP author] = 1; if (!($0 in touched)) { touched[$0] = 0; order[++n] = $0 } }
        END {
            for (k in seen) { split(k, p, SUBSEP); counts[p[1]]++ }
            for (i = 1; i <= n; i++) printf "%d\t%s\n", counts[order[i]] + 0, order[i]
        }' | sort -rn >"$tmp_authors"

cutoff="$(( $(date +%s) - branch_days * 86400 ))"
while read -r ts ref; do
    [ "$ts" -ge "$cutoff" ] || continue
    case "$ref" in
    refs/remotes/origin/HEAD | refs/remotes/origin/master) continue ;;
    esac
    git diff --name-only "$trunk...$ref" 2>/dev/null | sed "s|\$|\t${ref#refs/remotes/origin/}|"
done < <(git for-each-ref --sort=-committerdate \
    --format='%(committerdate:unix) %(refname)' refs/remotes/origin) >"$tmp_raw"

# Counted outside the loop on purpose: anything inside a pipeline runs in a
# subshell, and its counters evaporate.
scanned="$(cut -f2 "$tmp_raw" | sort -u | wc -l | tr -d ' ')"

awk -F'\t' -v skip="$skip_re" '$1 !~ skip { c[$1]++; b[$1] = b[$1] " " $2 }
    END { for (f in c) printf "%d\t%s\t%s\n", c[f], f, b[f] }' "$tmp_raw" |
    sort -rn >"$tmp_branches"

emit() {
    printf '<!-- generated by tools/agents/hot-files.sh -- do not edit by hand -->\n'
    printf '<!-- regenerate: tools/agents/hot-files.sh -->\n\n'
    printf '# Hot files\n\n'
    printf 'Generated %s from `%s` (author window %sd, %s active branches scanned).\n\n' \
        "$(date -u +%Y-%m-%d)" "$trunk" "$window" "$scanned"
    printf 'Two lists, because they answer different questions. **Authors** is where review\n'
    printf 'arguments happen. **Branches** is where the next conflict is. A file high on both\n'
    printf 'needs an append-only registry or a new slice file, not a careful releaser.\n\n'

    printf 'Bot-owned trees (`externals/`, `dist/languages/`, non-English `values-*/`) are\n'
    printf 'excluded on purpose: they churn weekly and are the cheapest conflict to avoid.\n\n'
    printf '## Most distinct authors (%sd)\n\n' "$window"
    printf '| authors | file |\n|---:|---|\n'
    head -n 20 "$tmp_authors" | while IFS=$'\t' read -r n f; do
        printf '| %s | `%s` |\n' "$n" "$f"
    done
    printf '\n## Touched by the most active branches (%sd)\n\n' "$branch_days"
    printf '| branches | file | which |\n|---:|---|---|\n'
    head -n 20 "$tmp_branches" | while IFS=$'\t' read -r n f rest; do
        printf '| %s | `%s` | %s |\n' "$n" "$f" \
            "$(printf '%s' "$rest" | tr ' ' '\n' | grep -v '^$' | sed 's/^/`/;s/$/`/' | paste -sd' ' -)"
    done
    printf '\n## Rules that follow from this list\n\n'
    printf -- '- New settings go at the **end** of their category block in `src/common/settings.h`; never reorder.\n'
    printf -- '- New behaviour goes in a new slice file with one registration line, not into a hot monolith.\n'
    printf -- '- `dist/languages/*` and locale `strings.xml` are bot-owned: edit English source only.\n'
    printf -- '- Claim the files in the issue before editing them: `tools/agents/claim.sh`.\n'
}

if [ "$print_only" = true ]; then
    emit
else
    mkdir -p docs/agents
    emit >"$out"
    agent_ok "wrote $out"
fi
