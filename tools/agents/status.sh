# What is in flight, parsed from branch names plus the issue tracker. The name
# is the database: kind, owner, area, issue and slug all come out of it.
#
#   tools/agents/status.sh              # print the table
#   tools/agents/status.sh --write      # also regenerate docs/agents/work-in-flight.md
#   tools/agents/status.sh --all        # include branches that break the grammar

here="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=tools/agents/lib.sh
. "$here/lib.sh"

write=false
conforming_only=false
days=45

while [ $# -gt 0 ]; do
    case "$1" in
    -h | --help)
        cat <<'EOF'
Usage: tools/agents/status.sh [--write] [--conforming-only] [--days N]

  --write            regenerate docs/agents/work-in-flight.md from live state
  --conforming-only  hide legacy-named branches (they show as state=legacy by default)
  --days N           age window for "active" (default 45)

Legacy-named branches are listed on purpose: the graveyard is the finding.
EOF
        exit 0
        ;;
    --write)
        write=true
        shift
        ;;
    --conforming-only)
        conforming_only=true
        shift
        ;;
    --days)
        days="${2:-45}"
        shift 2
        ;;
    *)
        agent_die "unknown argument $1"
        ;;
    esac
done

root="$(agent_repo_root)"
cd "$root"
trunk="$(agent_trunk_ref)" || agent_die "no master ref"

# ---- issue state ------------------------------------------------------------
issues_json=""
if agent_have gh; then
    issues_json="$(gh issue list --state all --limit 300 --json number,state,title,labels 2>/dev/null || true)"
fi

issue_state() {
    local n="$1"
    [ -n "$issues_json" ] || {
        printf '?'
        return
    }
    if agent_have jq; then
        printf '%s' "$issues_json" | jq -r --arg n "$n" \
            '.[] | select(.number == ($n | tonumber)) | .state' 2>/dev/null | head -n1
    else
        printf '?'
    fi
}

# ---- rows -------------------------------------------------------------------
cutoff="$(( $(date +%s) - days * 86400 ))"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

printf '| age | area | owner | issue | state | branch | ahead/behind |\n' >"$tmp"
printf '|---|---|---|---|---|---|---|\n' >>"$tmp"

legacy=0
while read -r ts ref; do
    name="${ref#refs/remotes/origin/}"
    case "$name" in
    HEAD | master) continue ;;
    esac
    [ "$ts" -ge "$cutoff" ] || continue
    if agent_branch_valid "$name"; then
        area="$(agent_branch_field "$name" area)"
        owner="$(agent_branch_field "$name" owner)"
        issue="$(agent_branch_field "$name" issue)"
    else
        # Legacy names are the point of this table: the graveyard has to be
        # visible, or "just rebase before PR" advice keeps being ignored.
        if [ "$conforming_only" = true ]; then
            continue
        fi
        legacy=$((legacy + 1))
        area="-" owner="-" issue="-"
    fi
    state="-"
    case "$issue" in
    [0-9]*) state="$(issue_state "$issue")" ;;
    esac
    [ -n "$state" ] || state="?"
    if agent_branch_valid "$name"; then :; else state="legacy"; fi
    counts="$(git rev-list --left-right --count "$trunk...$ref" 2>/dev/null | awk '{print $1"/"$2}')"
    age="$(( ($(date +%s) - ts) / 86400 ))d"
    printf '| %s | %s | %s | %s | %s | `%s` | %s |\n' \
        "$age" "$area" "$owner" "$issue" "$state" "$name" "${counts:-?}" >>"$tmp"
done < <(git for-each-ref --sort=-committerdate \
    --format='%(committerdate:unix) %(refname)' refs/remotes/origin)

rows=$(( $(wc -l <"$tmp") - 2 ))
if [ "$rows" -le 0 ]; then
    agent_warn "no active branches in the last ${days}d"
fi
[ "$legacy" -gt 0 ] && agent_warn "$legacy of $rows active branches are legacy-named (state=legacy); recreate them through branch.sh before adding commits"

cat "$tmp"

if [ "$write" = true ]; then
    {
        printf '<!-- generated by tools/agents/status.sh -- do not edit by hand -->\n'
        printf '<!-- regenerate: tools/agents/status.sh --write -->\n\n'
        printf '# Work in flight\n\n'
        printf 'Snapshot: %s, active window %sd, trunk `%s`.\n\n' \
            "$(date -u +%Y-%m-%dT%H:%MZ)" "$days" "$trunk"
        cat "$tmp"
        printf '\nRows in `?` mean the branch name did not parse or no issue state was available.\n'
    } >docs/agents/work-in-flight.md
    agent_ok "wrote docs/agents/work-in-flight.md ($rows rows)"
fi
